"""Convert Anime4K v3.2 mpv GLSL upscalers (MIT, bloc97) into D3D11 pixel shaders.

Input : src/shaders/third_party/anime4k/Anime4K_Upscale_CNN_x2_{S,M,L,VL,UL}.glsl
Output: src/shaders/anime4k/<size>_<pass>.hlsl  (one entry `main` per file, compiled by build.rs with fxc)
        src/a4k_passes.rs                         (pass graph: inputs, output, 2x flag)

Run from the repository root:  python tools/anime4k_convert.py
The conversion is mechanical: mpv hook macros become texture loads, `mat4(...) * v` becomes
`mul(v, float4x4(...))` (GLSL fills columns, HLSL fills rows, so the product is identical).
"""
import pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src/shaders/third_party/anime4k"
OUT = ROOT / "src/shaders/anime4k"
SIZES = ["S", "M", "L", "VL", "UL"]

HEADER = """// Generated by tools/anime4k_convert.py from Anime4K v3.2 (MIT License, Copyright (c) 2019-2021 bloc97).
// Do not edit by hand. See licenses/LICENSE-Anime4K.txt.
cbuffer C : register(b0) { float4 g_src; float4 g_dst; };
SamplerState sLin : register(s0);
SamplerState sPt  : register(s1);
"""


def parse(path):
    passes, cur = [], None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("//!DESC"):
            cur = {"binds": [], "save": None, "x2": False, "code": []}
            passes.append(cur)
        elif cur is None:
            continue
        elif line.startswith("//!BIND"):
            cur["binds"].append(line.split()[1])
        elif line.startswith("//!SAVE"):
            cur["save"] = line.split()[1]
        elif line.startswith("//!WIDTH"):
            cur["x2"] = line.strip().endswith("2 *")
        elif line.startswith("//!"):
            continue
        else:
            cur["code"].append(line)
    return passes


def convert(code, binds):
    src = "\n".join(code)
    # 3x3 convolutions use go_N(x, y); 1x1 convolutions use the argument-less g_N.
    src = re.sub(r"mat4\(([^)]*)\) \* (go_\d+\([^()]*\)|g_\d+\b)", r"mul(\2, float4x4(\1))", src)
    src = re.sub(r"\bvec([234])\(([^(),]*)\)", r"((float\1)(\2))", src)
    src = re.sub(r"\bivec([234])\b", r"int\1", src)
    src = re.sub(r"\bvec([234])\b", r"float\1", src)
    src = src.replace("fract(", "frac(")
    src = src.replace("float4 hook()", "float4 main(float4 pos : SV_Position) : SV_Target")
    # Per-texture accessors; every conv pass runs at its input's resolution, so the output pixel is the input texel.
    defs = []
    for i, name in enumerate(binds):
        defs.append(f"Texture2D<float4> T{i} : register(t{i});")
    defs.append("#define A4K_UV ((pos.xy - g_dst.xy) / g_dst.zw)")
    for i, name in enumerate(binds):
        defs.append(f"#define {name}_texOff(o) T{i}.Load(int3(clamp(int2(pos.xy) + int2(o), int2(0, 0), int2(A4K_SIZE({i})) - 1), 0))")
        samp = "sLin" if name == "MAIN" else "sPt"
        defs.append(f"#define {name}_tex(uv) T{i}.SampleLevel({samp}, (uv), 0)")
        defs.append(f"#define {name}_pos A4K_UV")
        defs.append(f"#define {name}_size A4K_SIZE({i})")
        defs.append(f"#define {name}_pt (1.0 / A4K_SIZE({i}))")
    defs.append("float2 A4K_SIZE(uint i) { uint w = 1, h = 1;")
    for i in range(len(binds)):
        defs.append(f"    if (i == {i}) T{i}.GetDimensions(w, h);")
    defs.append("    return float2(w, h); }")
    return HEADER + "\n".join(defs) + "\n" + src + "\n"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for f in OUT.glob("*.hlsl"):
        f.unlink()
    rs = ["// Generated by tools/anime4k_convert.py. Do not edit by hand.",
          "/// One Anime4K pass: texture ids it reads (0 = source image) and the id it writes (255 = the final 2x image).",
          "pub struct Pass { pub file: &'static str, pub inputs: &'static [u8], pub output: u8 }"]
    for size in SIZES:
        passes = parse(SRC / f"Anime4K_Upscale_CNN_x2_{size}.glsl")
        ids = {"MAIN": 0}
        rows = []
        for k, p in enumerate(passes):
            name = f"{size.lower()}_{k}"
            (OUT / f"{name}.hlsl").write_text(convert(p["code"], p["binds"]), encoding="utf-8")
            if p["save"] == "MAIN":
                assert p["x2"], "only the final depth-to-space pass doubles the resolution"
                out = 255
            else:
                out = ids.setdefault(p["save"], len(ids))
            inputs = ", ".join(str(ids[b]) for b in p["binds"])
            rows.append(f'    Pass {{ file: "{name}", inputs: &[{inputs}], output: {out} }},')
        rs.append(f"pub const {size}: &[Pass] = &[")
        rs += rows
        rs.append("];")
        rs.append(f"pub const {size}_TEXTURES: usize = {len(ids)};")
    (ROOT / "src/a4k_passes.rs").write_text("\n".join(rs) + "\n", encoding="utf-8")
    print("ok", sum(1 for _ in OUT.glob("*.hlsl")), "passes")


if __name__ == "__main__":
    main()
